// Generates offline-manifest.json — the exact list of media files the
// "Download family for offline use" button (Parent Settings) caches so the app
// works on a plane / with no internet.
//
// What it lists:
//   shared  → every file under audio/        (animal sounds + learning voice clips)
//   mascots → every file under mascots/<id>/green/  (the chroma video + voice
//             clips the app actually plays; the legacy top-level idle/video/audio
//             siblings are NOT used because all mascots are green-screen/chroma)
//
// App shell (HTML/JS/CSS/body images/icons/fonts) is already precached by sw.js,
// so it is intentionally NOT repeated here.
//
// Re-run after adding/removing media:  node scripts/gen-offline-manifest.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, posix } from 'node:path';

const ROOT = process.cwd();
const MASCOTS = ['dog', 'tiger', 'giraffe', 'panda', 'orca', 'eagle'];
const MEDIA_EXT = new Set(['.mp4', '.mp3']);  // skip dev proofs (*.png) + html

function walk(rel) {
  const out = [];
  let entries;
  try { entries = readdirSync(join(ROOT, rel), { withFileTypes: true }); }
  catch { return out; }  // missing dir → empty
  for (const e of entries) {
    const childRel = posix.join(rel, e.name);
    if (e.isDirectory()) { out.push(...walk(childRel)); continue; }
    const dot = e.name.lastIndexOf('.');
    const ext = dot >= 0 ? e.name.slice(dot).toLowerCase() : '';
    if (!MEDIA_EXT.has(ext)) continue;
    out.push({ p: './' + childRel, b: statSync(join(ROOT, childRel)).size });
  }
  return out;
}

const sum = files => files.reduce((s, f) => s + f.b, 0);

const sharedFiles = walk('audio');
const mascots = {};
for (const id of MASCOTS) {
  const files = walk(`mascots/${id}/green`);
  mascots[id] = { bytes: sum(files), files };
}

const manifest = {
  generatedAt: new Date().toISOString(),
  note: 'AUTO-GENERATED by scripts/gen-offline-manifest.mjs — do not hand-edit.',
  shared: { bytes: sum(sharedFiles), files: sharedFiles },
  mascots,
};

writeFileSync(join(ROOT, 'offline-manifest.json'), JSON.stringify(manifest));

const mb = n => (n / 1048576).toFixed(1);
console.log('shared :', String(sharedFiles.length).padStart(4), 'files', mb(manifest.shared.bytes).padStart(6), 'MB');
for (const id of MASCOTS) {
  console.log((id + ' ').padEnd(8) + ':', String(mascots[id].files.length).padStart(4), 'files', mb(mascots[id].bytes).padStart(6), 'MB');
}
